-- A ordem dos parâmetros importa: a API chama as procedures de forma posicional (EXEC proc ?, ?, ...).

CREATE OR ALTER PROCEDURE dbo.SP_MEDICACOES_CADASTRAR
    @DS_NOME                VARCHAR(150),
    @DS_PRINCIPIO_ATIVO     VARCHAR(150),
    @DS_FABRICANTE          VARCHAR(150),
    @DS_FORMA_FARMACEUTICA  VARCHAR(50),
    @DS_DOSAGEM             VARCHAR(50),
    @FL_CONTROLADA          BIT,
    @DS_OBSERVACOES         VARCHAR(500)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF EXISTS (
        SELECT 1 FROM dbo.TB_MEDICACOES
        WHERE DS_NOME = @DS_NOME AND DS_DOSAGEM = @DS_DOSAGEM AND DS_FORMA_FARMACEUTICA = @DS_FORMA_FARMACEUTICA
    )
        THROW 50001, 'Medicação já cadastrada com este nome, dosagem e forma farmacêutica!', 1;

    INSERT INTO dbo.TB_MEDICACOES (DS_NOME, DS_PRINCIPIO_ATIVO, DS_FABRICANTE, DS_FORMA_FARMACEUTICA, DS_DOSAGEM, FL_CONTROLADA, DS_OBSERVACOES, FL_ATIVO)
    VALUES (@DS_NOME, @DS_PRINCIPIO_ATIVO, @DS_FABRICANTE, @DS_FORMA_FARMACEUTICA, @DS_DOSAGEM, ISNULL(@FL_CONTROLADA, 0), @DS_OBSERVACOES, 1);

    SELECT CAST(SCOPE_IDENTITY() AS INT) AS PK_ID;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_MEDICACOES_ATUALIZAR
    @PK_ID                  INT,
    @DS_NOME                VARCHAR(150),
    @DS_PRINCIPIO_ATIVO     VARCHAR(150),
    @DS_FABRICANTE          VARCHAR(150),
    @DS_FORMA_FARMACEUTICA  VARCHAR(50),
    @DS_DOSAGEM             VARCHAR(50),
    @FL_CONTROLADA          BIT,
    @DS_OBSERVACOES         VARCHAR(500)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_MEDICACOES WHERE PK_ID = @PK_ID)
        THROW 50002, 'Medicação não encontrada!', 1;

    IF EXISTS (
        SELECT 1 FROM dbo.TB_MEDICACOES
        WHERE PK_ID <> @PK_ID AND DS_NOME = @DS_NOME AND DS_DOSAGEM = @DS_DOSAGEM AND DS_FORMA_FARMACEUTICA = @DS_FORMA_FARMACEUTICA
    )
        THROW 50001, 'Medicação já cadastrada com este nome, dosagem e forma farmacêutica!', 1;

    UPDATE dbo.TB_MEDICACOES
    SET DS_NOME = @DS_NOME,
        DS_PRINCIPIO_ATIVO = @DS_PRINCIPIO_ATIVO,
        DS_FABRICANTE = @DS_FABRICANTE,
        DS_FORMA_FARMACEUTICA = @DS_FORMA_FARMACEUTICA,
        DS_DOSAGEM = @DS_DOSAGEM,
        FL_CONTROLADA = ISNULL(@FL_CONTROLADA, 0),
        DS_OBSERVACOES = @DS_OBSERVACOES
    WHERE PK_ID = @PK_ID;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_MEDICACOES_DESATIVAR
    @PK_ID INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_MEDICACOES WHERE PK_ID = @PK_ID)
        THROW 50002, 'Medicação não encontrada!', 1;

    UPDATE dbo.TB_MEDICACOES SET FL_ATIVO = 0 WHERE PK_ID = @PK_ID;
END
GO
