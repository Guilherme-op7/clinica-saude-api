-- A ordem dos parâmetros importa: a API chama as procedures de forma posicional (EXEC proc ?, ?, ...).

CREATE OR ALTER PROCEDURE dbo.SP_PACIENTES_CADASTRAR
    @DS_NOME                VARCHAR(255),
    @NR_CPF                 VARCHAR(14),
    @NR_CARTAO_SUS          VARCHAR(30),
    @DT_NASCIMENTO          SMALLDATETIME,
    @TP_SEXO                VARCHAR(1),
    @DS_TELEFONE            VARCHAR(20),
    @DS_EMAIL               VARCHAR(100),
    @DS_ENDERECO            VARCHAR(255),
    @DS_TIPO_SANGUINEO      VARCHAR(5),
    @DS_ALERGIAS            VARCHAR(500),
    @DS_CONTATO_EMERGENCIA  VARCHAR(255)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @NR_CPF IS NOT NULL AND EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WITH (UPDLOCK, HOLDLOCK) WHERE NR_CPF = @NR_CPF)
        THROW 50020, 'CPF já cadastrado!', 1;

    IF @NR_CARTAO_SUS IS NOT NULL AND EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WHERE NR_CARTAO_SUS = @NR_CARTAO_SUS)
        THROW 50021, 'Cartão do SUS já cadastrado!', 1;

    INSERT INTO dbo.TB_PACIENTES (DS_NOME, NR_CPF, NR_CARTAO_SUS, DT_NASCIMENTO, TP_SEXO, DS_TELEFONE, DS_EMAIL, DS_ENDERECO, DS_TIPO_SANGUINEO, DS_ALERGIAS, DS_CONTATO_EMERGENCIA, TP_STATUS)
    VALUES (@DS_NOME, @NR_CPF, @NR_CARTAO_SUS, @DT_NASCIMENTO, @TP_SEXO, @DS_TELEFONE, @DS_EMAIL, @DS_ENDERECO, @DS_TIPO_SANGUINEO, @DS_ALERGIAS, @DS_CONTATO_EMERGENCIA, 'ativo');

    SELECT CAST(SCOPE_IDENTITY() AS INT) AS PK_ID;
END
GO

CREATE OR ALTER PROCEDURE dbo.SP_PACIENTES_ATUALIZAR
    @PK_ID                  INT,
    @DS_NOME                VARCHAR(255),
    @NR_CPF                 VARCHAR(14),
    @NR_CARTAO_SUS          VARCHAR(30),
    @DT_NASCIMENTO          SMALLDATETIME,
    @TP_SEXO                VARCHAR(1),
    @DS_TELEFONE            VARCHAR(20),
    @DS_EMAIL               VARCHAR(100),
    @DS_ENDERECO            VARCHAR(255),
    @DS_TIPO_SANGUINEO      VARCHAR(5),
    @DS_ALERGIAS            VARCHAR(500),
    @DS_CONTATO_EMERGENCIA  VARCHAR(255)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WHERE PK_ID = @PK_ID)
        THROW 50022, 'Paciente não encontrado!', 1;

    IF @NR_CPF IS NOT NULL AND EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WHERE PK_ID <> @PK_ID AND NR_CPF = @NR_CPF)
        THROW 50020, 'CPF já cadastrado!', 1;

    IF @NR_CARTAO_SUS IS NOT NULL AND EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WHERE PK_ID <> @PK_ID AND NR_CARTAO_SUS = @NR_CARTAO_SUS)
        THROW 50021, 'Cartão do SUS já cadastrado!', 1;

    UPDATE dbo.TB_PACIENTES
    SET DS_NOME = @DS_NOME,
        NR_CPF = @NR_CPF,
        NR_CARTAO_SUS = @NR_CARTAO_SUS,
        DT_NASCIMENTO = @DT_NASCIMENTO,
        TP_SEXO = @TP_SEXO,
        DS_TELEFONE = @DS_TELEFONE,
        DS_EMAIL = @DS_EMAIL,
        DS_ENDERECO = @DS_ENDERECO,
        DS_TIPO_SANGUINEO = @DS_TIPO_SANGUINEO,
        DS_ALERGIAS = @DS_ALERGIAS,
        DS_CONTATO_EMERGENCIA = @DS_CONTATO_EMERGENCIA
    WHERE PK_ID = @PK_ID;
END
GO

-- Soft delete: inativa o paciente e o login vinculado a ele (se houver).
CREATE OR ALTER PROCEDURE dbo.SP_PACIENTES_DESATIVAR
    @PK_ID INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM dbo.TB_PACIENTES WHERE PK_ID = @PK_ID)
        THROW 50022, 'Paciente não encontrado!', 1;

    BEGIN TRANSACTION;

    UPDATE dbo.TB_PACIENTES SET TP_STATUS = 'inativo' WHERE PK_ID = @PK_ID;
    UPDATE dbo.TB_USUARIOS SET FL_ATIVO = 0 WHERE FK_PACIENTE = @PK_ID;

    COMMIT TRANSACTION;
END
GO
