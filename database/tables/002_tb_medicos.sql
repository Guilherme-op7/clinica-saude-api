-- Pré-requisitos: TB_FUNCIONARIOS e TB_ESPECIALIDADES
IF OBJECT_ID('dbo.TB_MEDICOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_MEDICOS (
        PK_ID               INT IDENTITY(1,1) NOT NULL,
        FK_FUNCIONARIO      INT               NOT NULL, -- todo médico é um funcionário (nome, e-mail, telefone ficam lá)
        FK_ESPECIALIDADE    INT               NOT NULL,
        NR_CRM              VARCHAR(20)       NOT NULL,
        DS_UF_CRM           CHAR(2)           NOT NULL,
        FL_ATIVO            BIT               NOT NULL CONSTRAINT DF_TB_MEDICOS_FL_ATIVO DEFAULT 1,
        CONSTRAINT PK_TB_MEDICOS PRIMARY KEY CLUSTERED (PK_ID),
        CONSTRAINT UQ_TB_MEDICOS_FUNCIONARIO UNIQUE (FK_FUNCIONARIO),
        CONSTRAINT UQ_TB_MEDICOS_CRM UNIQUE (NR_CRM, DS_UF_CRM),
        CONSTRAINT FK_TB_MEDICOS_FUNCIONARIO FOREIGN KEY (FK_FUNCIONARIO) REFERENCES dbo.TB_FUNCIONARIOS (PK_ID),
        CONSTRAINT FK_TB_MEDICOS_ESPECIALIDADE FOREIGN KEY (FK_ESPECIALIDADE) REFERENCES dbo.TB_ESPECIALIDADES (PK_ID)
    )
END
GO
