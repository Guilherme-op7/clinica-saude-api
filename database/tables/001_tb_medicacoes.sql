IF OBJECT_ID('dbo.TB_MEDICACOES', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_MEDICACOES (
        PK_ID                   INT IDENTITY(1,1) NOT NULL,
        DS_NOME                 VARCHAR(150)      NOT NULL,
        DS_PRINCIPIO_ATIVO      VARCHAR(150)      NULL,
        DS_FABRICANTE           VARCHAR(150)      NULL,
        DS_FORMA_FARMACEUTICA   VARCHAR(50)       NOT NULL, -- comprimido, xarope, injetável...
        DS_DOSAGEM              VARCHAR(50)       NOT NULL, -- ex.: 500 mg
        FL_CONTROLADA           BIT               NOT NULL CONSTRAINT DF_TB_MEDICACOES_FL_CONTROLADA DEFAULT 0,
        DS_OBSERVACOES          VARCHAR(500)      NULL,
        FL_ATIVO                BIT               NOT NULL CONSTRAINT DF_TB_MEDICACOES_FL_ATIVO DEFAULT 1,
        CONSTRAINT PK_TB_MEDICACOES PRIMARY KEY CLUSTERED (PK_ID),
        CONSTRAINT UQ_TB_MEDICACOES_NOME_DOSAGEM_FORMA UNIQUE (DS_NOME, DS_DOSAGEM, DS_FORMA_FARMACEUTICA)
    )
END
GO
